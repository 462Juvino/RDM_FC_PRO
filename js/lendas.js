function injetarLendasNoJogo(){
    // Injeta em um time especial chamado Lendas_Futebol
    db.ref('banco_global_times/Lendas_Futebol').set({
        divisao: 'L',
        forca_base: 0,
        escudo_base64: 'https://cdn-icons-png.flaticon.com/512/1828/1828970.png',
        jogadores: BANCO_LENDAS
    }).then(()=>{
        alert('✅ ' + Object.keys(BANCO_LENDAS).length + ' LENDAS injetadas em Lendas_Futebol!');
    }).catch(e=> alert('Erro: ' + e.message));
}

function adicionarLendaAoMercado(nomeId){
    // Adiciona uma lenda específica aos Agentes Livres da sua liga
    let liga = document.getElementById('gerenciar-liga-id')?.value || document.getElementById('sorteio-liga-id')?.value || prompt('Código da liga:');
    if(!liga) return;
    let lenda = BANCO_LENDAS[nomeId];
    if(!lenda) return alert('Lenda não encontrada!');
    db.ref(`banco_global_times/Agentes_Livres_${liga}/jogadores/${nomeId}_Lenda`).set(lenda).then(()=>{
        alert(`✅ ${lenda.nome} adicionado aos Agentes Livres da liga ${liga}!`);
    });
}
